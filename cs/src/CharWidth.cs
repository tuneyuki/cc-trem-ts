        /// <summary>コードポイントの表示幅(0 / 1 / 2)。</summary>
        public static int Of(int cp)
        {
            if (cp < 0x0300) return 1; // ASCII・ラテン基本は即答(大半はここ)
            if (InRanges(Zero, cp)) return 0;
            if (cp >= 0x1100 && InRanges(Wide, cp)) return 2;
            return 1;
        }

        private static bool InRanges(int[] ranges, int cp)
        {
            if (cp < ranges[0] || cp > ranges[ranges.Length - 1]) return false;
            // 範囲の組を二分探索する。
            int lo = 0;
            int hi = ranges.Length / 2 - 1;
            while (lo <= hi)
            {
                int mid = (lo + hi) / 2;
                if (cp < ranges[mid * 2]) hi = mid - 1;
                else if (cp > ranges[mid * 2 + 1]) lo = mid + 1;
                else return true;
            }
            return false;
        }
    }
